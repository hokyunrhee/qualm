"""Which changed files the gate judges, and what in the repository it is allowed to trust.

The rule throughout: a pull request may not decide how it is judged. Configuration, keeps,
skip patterns and git attributes come from the base commit. A file is skipped as vendored,
generated or built only when the base commit already treated that place that way; a new file
that merely claims to be generated, or a new directory named vendor/, is judged like any
other code. Edits to the gate's own configuration are named in the report's warnings.
"""
import fnmatch, hashlib, json, os, posixpath, re

from . import gitio, lexer

CONFIG_NAMES = ('qualm.json', '.qualm.json')
GATE_WORDS = re.compile(r'\b(qualm|simplify-gate|gatecore)\b')
GENERATED_HEADER = re.compile(r'(?:Code generated\b.*\bDO NOT EDIT|@generated\b|<auto-generated|Autogenerated by|This file (?:is|was) (?:automatically )?generated|DO NOT EDIT[.!]? *(?:THIS FILE)?.*generated)', re.I)
GENERATOR_NAME = re.compile(r'Code generated (?:by )?(\S+)', re.I)
GENERATED_NAMES = ('*.pb.go', '*_pb2.py', '*_pb2_grpc.py', '*.pb.ts', '*_generated.*', '*.generated.*', '*.g.dart', '*_gen.go', 'zz_generated*')
VENDOR_DIRS = ('vendor', 'third_party', 'node_modules', 'third-party', 'external')
BUILD_DIRS = ('dist', 'build', 'out', 'target', 'bin', 'obj', '.next', 'coverage')
LOCKFILES = ('*.lock', 'package-lock.json', 'go.sum', 'pnpm-lock.yaml', 'yarn.lock', 'Gemfile.lock', 'poetry.lock', 'Cargo.lock')


def is_test(path, language):
    p = '/' + path
    name = posixpath.basename(path)
    low = name.lower()
    if language == 'Go':
        return name.endswith('_test.go') or '/testdata/' in p
    if language == 'Python':
        return bool(fnmatch.fnmatchcase(low, 'test_*.py') or low.endswith('_test.py') or low == 'conftest.py'
                    or re.search(r'/(tests?|testing)/', p))
    if language in ('TypeScript', 'JavaScript'):
        return bool(re.search(r'\.(test|spec|e2e|stories)\.[cm]?[jt]sx?$', low) or re.search(r'/(__tests__|__mocks__|tests?|e2e|cypress|playwright)/', p))
    if language == 'Ruby':
        return bool(low.endswith(('_spec.rb', '_test.rb')) or re.search(r'/(spec|test|features)/', p))
    if language == 'Java':
        return bool('/src/test/' in p or re.search(r'(Test|Tests|IT|TestCase)\.java$', name) or '/src/testFixtures/' in p)
    return bool(re.search(r'/(tests?|spec)/', p))


def is_minified(text):
    lines = text.split('\n')
    if not lines:
        return False
    longest = max(len(l) for l in lines)
    avg = len(text) / max(1, len(lines))
    return (avg > 300 and len(lines) < 400) or (longest > 5000 and avg > 200)


def content_hash(text):
    """What a keep binds to: the file's text with line endings and trailing spaces normalized."""
    norm = '\n'.join(l.rstrip() for l in (text or '').replace('\r\n', '\n').split('\n')).strip('\n')
    return hashlib.sha256(norm.encode('utf-8', 'replace')).hexdigest()


class Policy:
    """The gate's settings, read from the base commit only."""

    def __init__(self, data=None, source=None):
        data = data or {}
        self.source = source
        self.skip = [s for s in data.get('skip') or [] if isinstance(s, str)]
        self.keeps = [k for k in data.get('keeps') or data.get('keep') or [] if isinstance(k, dict)]
        g = data.get('next') or {}
        self.threshold = g.get('threshold') if isinstance(g.get('threshold'), (int, float)) and 0 < g.get('threshold') < 1 else None


def load_policy(repo, base):
    for name in CONFIG_NAMES:
        text = gitio.base_file(repo, base, name)
        if text is None:
            continue
        try:
            data = json.loads(text)
        except ValueError:
            raise gitio.GateError('%s in the base commit is not valid JSON' % name)
        if not isinstance(data, dict):
            raise gitio.GateError('%s in the base commit is not a JSON object' % name)
        return Policy(data, name)
    return Policy()


def external_keeps(repo):
    """Keeps a maintainer granted outside the pull request: a JSON file named by GATE_KEEPS_FILE,
    which must live outside the checkout (CI writes it from a label or an approved comment)."""
    path = os.environ.get('GATE_KEEPS_FILE')
    if not path:
        return [], None
    real = os.path.realpath(path)
    root = os.path.realpath(repo)
    if real == root or real.startswith(root + os.sep):
        return [], 'GATE_KEEPS_FILE points inside the checkout, where the pull request can write it; it was ignored.'
    try:
        data = json.load(open(real))
    except (OSError, ValueError):
        return [], 'GATE_KEEPS_FILE could not be read as JSON; no keeps applied.'
    rows = data.get('keeps') if isinstance(data, dict) else data
    return [k for k in rows or [] if isinstance(k, dict)], None


class Decision:
    __slots__ = ('change', 'status', 'reason', 'language')

    def __init__(self, change, status, reason=None, language=None):
        self.change, self.status, self.reason, self.language = change, status, reason, language


def _dir_prefix(path, names):
    parts = path.split('/')
    for k, part in enumerate(parts[:-1]):
        if part in names:
            return '/'.join(parts[:k + 1])
    return None


def classify(repo, base, changes, include_tests=False, policy=None):
    """A Decision per changed file, plus warnings about the gate's own perimeter."""
    policy = policy or load_policy(repo, base)
    warnings = []
    keeps, warn = external_keeps(repo)
    if warn:
        warnings.append(warn)
    keeps = policy.keeps + keeps
    paths = [c.path for c in changes]
    attrs = gitio.attributes_from_base(repo, base, paths)
    base_tree_cache = {}

    def base_has_dir(d):
        if d not in base_tree_cache:
            out = gitio.git(repo, 'ls-tree', '--name-only', base, '--', d, check=False).strip()
            base_tree_cache[d] = bool(out)
        return base_tree_cache[d]

    generators_in_base = {}

    def base_uses_generator(name):
        if name not in generators_in_base:
            out = gitio.git(repo, 'grep', '-l', '-F', '-I', '--max-count=1', '-e', 'Code generated by ' + name, base, '--', check=False)
            generators_in_base[name] = bool(out.strip())
        return generators_in_base[name]

    changed_sources = {c.path for c in changes if c.path.endswith(('.proto', '.graphql', '.gql', '.thrift', '.fbs', '.avsc', '.openapi.yaml', '.swagger.json'))}
    decisions = []
    for c in changes:
        lang = lexer.language_of(c.path)
        a = attrs.get(c.path, {})
        name = posixpath.basename(c.path)
        # the gate's own configuration
        if name in CONFIG_NAMES and '/' not in c.path:
            warnings.append('This change edits %s, the gate\'s configuration. The gate reads its configuration from the base '
                            'commit, so the edit takes effect only after a maintainer merges it.' % c.path)
        if name == '.gitattributes':
            warnings.append('This change edits %s. The gate reads git attributes from the base commit, so the edit does not '
                            'change how this pull request is judged.' % c.path)
        if c.path.startswith('.github/workflows/') or c.path in ('.gitlab-ci.yml', '.circleci/config.yml'):
            base_text = c.base or ''
            if GATE_WORDS.search(base_text) or GATE_WORDS.search(c.head or ''):
                warnings.append('This change edits %s, a CI workflow that runs the gate. A maintainer should review that '
                                'edit: a workflow from a pull request can skip or weaken the gate.' % c.path)
        if c.head_is_symlink:
            decisions.append(Decision(c, 'skipped', 'symlink', lang))
            continue
        if c.undecodable or c.head is None:
            if lang in lexer.JUDGED:
                decisions.append(Decision(c, 'error', 'the file is code but its bytes are not text the gate can read', lang))
            else:
                decisions.append(Decision(c, 'skipped', 'binary', lang))
            continue
        if any(fnmatch.fnmatchcase(name, g) for g in LOCKFILES):
            decisions.append(Decision(c, 'skipped', 'lockfile', lang))
            continue
        if lang not in lexer.JUDGED:
            decisions.append(Decision(c, 'skipped', 'not code in a judged language', lang))
            continue
        if any(fnmatch.fnmatchcase(c.path, g) or fnmatch.fnmatchcase(name, g) for g in policy.skip):
            decisions.append(Decision(c, 'skipped', 'skipped by %s in the base commit' % policy.source, lang))
            continue
        if a.get('linguist-generated') in ('set', 'true'):
            decisions.append(Decision(c, 'skipped', 'generated (git attributes of the base commit)', lang))
            continue
        if a.get('linguist-vendored') in ('set', 'true'):
            decisions.append(Decision(c, 'skipped', 'vendored (git attributes of the base commit)', lang))
            continue
        vdir = _dir_prefix(c.path, VENDOR_DIRS)
        if vdir and base_has_dir(vdir):
            decisions.append(Decision(c, 'skipped', 'vendored (%s/ exists in the base commit)' % vdir, lang))
            continue
        bdir = c.path.split('/')[0] if '/' in c.path and c.path.split('/')[0] in BUILD_DIRS else None
        if bdir and base_has_dir(bdir) and is_minified(c.head):
            decisions.append(Decision(c, 'skipped', 'build output (%s/ exists in the base commit)' % bdir, lang))
            continue
        head_top = '\n'.join(c.head.split('\n')[:8])
        if GENERATED_HEADER.search(head_top) or any(fnmatch.fnmatchcase(name, g) for g in GENERATED_NAMES):
            m = GENERATOR_NAME.search(head_top)
            trusted = False
            why = ''
            if c.base is not None and GENERATED_HEADER.search('\n'.join(c.base.split('\n')[:8])):
                trusted, why = True, 'the base version was generated too'
            elif m and base_uses_generator(m.group(1)):
                trusted, why = True, '%s already generates code in the base commit' % m.group(1)
            elif changed_sources:
                trusted, why = True, 'its source (%s) changed in this pull request' % sorted(changed_sources)[0]
            if trusted:
                decisions.append(Decision(c, 'skipped', 'generated (%s)' % why, lang))
                continue
        if is_minified(c.head):
            decisions.append(Decision(c, 'skipped', 'minified', lang))
            continue
        if not include_tests and is_test(c.path, lang):
            decisions.append(Decision(c, 'skipped', 'test', lang))
            continue
        h = content_hash(c.head)
        kept = next((k for k in keeps if k.get('path') == c.path and k.get('hash') == h), None)
        if kept:
            decisions.append(Decision(c, 'kept', str(kept.get('reason') or 'kept by a maintainer')[:300], lang))
            continue
        decisions.append(Decision(c, 'judged', None, lang))
    # a file skipped as a test that the judged code imports is code, not a test
    judged_text = '\n'.join(d.change.head or '' for d in decisions if d.status == 'judged')
    for d in decisions:
        if d.status == 'skipped' and d.reason == 'test' and d.change.status == 'A':
            stem = posixpath.splitext(posixpath.basename(d.change.path))[0]
            if len(stem) >= 4 and re.search(r'(import|require|from|load)\b[^\n]*\b' + re.escape(stem) + r'\b', judged_text):
                d.status, d.reason = 'judged', None
    return decisions, warnings


def cache_dir(repo):
    """Where a cache may live: GATE_CACHE_DIR or the user cache, never inside the checkout."""
    root = os.path.realpath(repo)
    d = os.environ.get('GATE_CACHE_DIR')
    if d:
        real = os.path.realpath(d)
        if real == root or real.startswith(root + os.sep):
            return None, 'GATE_CACHE_DIR is inside the checkout, where the pull request can write it; the cache was not used.'
        return real, None
    base = os.environ.get('XDG_CACHE_HOME') or os.path.join(os.path.expanduser('~'), '.cache')
    real = os.path.realpath(os.path.join(base, 'gatecore'))
    if real == root or real.startswith(root + os.sep):
        return None, 'The user cache directory is inside the checkout; the cache was not used.'
    return real, None
