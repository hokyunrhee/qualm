"""The comparison tables of next/REPORT.md, generated from eval/results/ so every number traces.

    python3 -I eval/report_tables.py > eval/results/report_tables.md

Dev numbers are repository-grouped out-of-fold scores (dev_oof_v3.json); c-llm was run on dev's
150-item subset only (dev150_v3.json). Held-out numbers are the one pre-registered run
(heldout_v1.json). A cell is "-" where a measurement does not exist, and the reason is in the notes.
"""
import json, os

R = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'results')
ORDER = ['a-baseline', 'a-recal', 'n0-size', 'b-offline', 'e-spot', 'c-llm', 'd-cascade']


def load(name):
    p = os.path.join(R, name)
    return json.load(open(p)) if os.path.exists(p) else None


def first(*names):
    for n in names:
        d = load(n)
        if d is not None:
            return d, n
    return None, None


DEV, DEV_NAME = first('dev_oof_v3.json', 'dev_oof_v2.json')
DEV150, DEV150_NAME = first('dev150_v3.json', 'dev150_v2.json')
HO = load('heldout_v1.json')
MATCHED = load('heldout_matched_fpr_v1.json')


def dev_cand(c):
    """(record, source) for a candidate on dev: the full dev split, or dev150 for c-llm."""
    if DEV and c in DEV['candidates']:
        return DEV['candidates'][c], ''
    if DEV150 and c in DEV150['candidates']:
        return DEV150['candidates'][c], ' †'
    return None, ''


def dev_vs(c, key='vs_baseline'):
    if DEV and c in DEV.get(key, {}):
        return DEV[key][c], ''
    if DEV150 and c in DEV150.get(key, {}):
        return DEV150[key][c], ' †'
    return None, ''


def f3(x):
    return '-' if x is None or x != x else '%.3f' % x


def ci(pair):
    return '' if not pair else ' [%.3f, %.3f]' % tuple(pair)


def sgn(x):
    return '-' if x is None else '%+.3f' % x


def diff_cell(v, metric):
    if not v or metric not in v:
        return '-'
    m = v[metric]
    return '%s [%s, %s]' % (sgn(m['diff']), sgn(m['ci95'][0]), sgn(m['ci95'][1]))


def table(head, rows):
    out = ['| ' + ' | '.join(head) + ' |', '|' + '---|' * len(head)]
    out += ['| ' + ' | '.join(r) + ' |' for r in rows]
    return '\n'.join(out)


def main():
    print('<!-- generated by eval/report_tables.py from %s, %s, heldout_v1.json; do not edit by hand -->\n' % (DEV_NAME, DEV150_NAME))
    print('Dev items %d (%d positives), held-out items %d (%d positives). † = dev150 subset (%d items, %d positives): c-llm was run on dev only there.\n'
          % (DEV['items'], DEV['positives'], HO['items'], HO['positives'], DEV150['items'], DEV150['positives']))

    print('**Table 2a. Ranking (threshold-free).** PR-AUC with a 95% repository-bootstrap interval, and ROC-AUC.\n')
    rows = []
    for c in ORDER:
        d, mark = dev_cand(c)
        h = HO['candidates'].get(c)
        rows.append([c,
                     (f3(d['pr_auc']) + ci(d.get('pr_auc_ci95')) + mark) if d else '-',
                     (f3(h['pr_auc']) + ci(h.get('pr_auc_ci95'))) if h else '-',
                     (f3(d['roc_auc']) + mark) if d else '-', f3(h['roc_auc']) if h else '-'])
    print(table(['candidate', 'PR-AUC dev', 'PR-AUC held-out', 'ROC-AUC dev', 'ROC-AUC held-out'], rows))

    print('\n**Table 2b. At each candidate\'s own gate.** Precision, recall, F1 and the false-alarm rate (share of negatives failed).\n')
    rows = []
    for c in ORDER:
        d, mark = dev_cand(c)
        h = HO['candidates'].get(c)
        row = [c]
        for k in ('precision', 'recall', 'f1', 'fpr'):
            row += [(f3(d.get(k)) + mark) if d else '-', f3(h.get(k)) if h else '-']
        rows.append(row)
    print(table(['candidate', 'precision dev', 'precision held-out', 'recall dev', 'recall held-out', 'F1 dev', 'F1 held-out',
                 'false alarms dev', 'false alarms held-out'], rows))

    print('\n**Table 2c. Calibration.** Brier score (lower is better) with its reliability part, log loss, and ECE over 10 equal-mass bins with a 95% interval. '
          'Held-out prevalence is 38% against dev\'s 22%, so held-out absolute calibration mixes the prior shift with miscalibration.\n')
    rows = []
    for c in ORDER:
        d, mark = dev_cand(c)
        h = HO['candidates'].get(c)
        row = [c]
        row += [(f3(d.get('brier')) + mark) if d else '-', f3(h['brier']) if h else '-']
        row += [(f3(d.get('brier_parts', {}).get('reliability')) + mark) if d else '-', f3(h['brier_parts']['reliability']) if h else '-']
        row += [(f3(d.get('log_loss')) + mark) if d else '-', f3(h['log_loss']) if h else '-']
        row += [(f3(d.get('ece_mass')) + ci(d.get('ece_mass_ci95')) + mark) if d else '-', (f3(h['ece_mass']) + ci(h.get('ece_mass_ci95'))) if h else '-']
        rows.append(row)
    print(table(['candidate', 'Brier dev', 'Brier held-out', 'reliability dev', 'reliability held-out', 'log loss dev', 'log loss held-out',
                 'ECE-mass dev', 'ECE-mass held-out'], rows))

    print('\n**Table 2d. Difference from a-baseline, paired, 95%% repository-bootstrap interval** (candidate minus baseline; for Brier, log loss, ECE and false alarms lower is better). '
          'Held-out p-values for PR-AUC, Holm-adjusted over the secondary family: %s.\n'
          % ', '.join('%s %.3f' % (k, v) for k, v in sorted(HO['holm_pr_auc']['adjusted_p'].items())))
    rows = []
    for c in ORDER[1:]:
        dv, mark = dev_vs(c)
        hv = HO['vs_baseline'].get(c)
        for metric in ('pr_auc', 'roc_auc', 'precision', 'recall', 'fpr', 'brier', 'log_loss', 'ece_mass'):
            rows.append([c if metric == 'pr_auc' else '', metric, diff_cell(dv, metric) + (mark if dv else ''), diff_cell(hv, metric)])
    print(table(['candidate', 'metric', 'dev', 'held-out'], rows))

    print('\n**Table 2e. PR-AUC difference from a-baseline within strata** (95% repository-bootstrap interval). '
          'Natural: reviewer-comment and follow-up positives against approved, post-fix and surviving negatives. '
          'Without hard negatives: renames, comment-only edits, reformatting and moves removed (25% of held-out negatives, 2.4% of dev\'s).\n')
    rows = []
    for c in ORDER[1:]:
        row = [c]
        for key in ('vs_baseline_natural', 'vs_baseline_natural_without_approved_agent', 'vs_baseline_without_hard_negatives'):
            dv, mark = dev_vs(c, key)
            hv = HO.get(key, {}).get(c)
            row += [diff_cell(dv, 'pr_auc') + (mark if dv else ''), diff_cell(hv, 'pr_auc')]
        rows.append(row)
    print(table(['candidate', 'natural dev', 'natural held-out', 'natural without approved_agent dev', 'natural without approved_agent held-out',
                 'without hard negatives dev', 'without hard negatives held-out'], rows))

    print('\n**Table 2f. Absolute PR-AUC within strata** (dev | held-out).\n')
    rows = []
    for c in ORDER:
        d, mark = dev_cand(c)
        h = HO['candidates'].get(c)
        row = [c]
        for key in ('natural', 'without_hard_negatives'):
            row += [(f3(d[key]['pr_auc']) + mark) if d and key in d else '-', f3(h[key]['pr_auc']) if h and key in h else '-']
        row += [(f3(d['pr_level']['pr_auc']) + mark) if d and 'pr_level' in d else '-', f3(h['pr_level']['pr_auc']) if h else '-']
        row += [(f3(d['pr_level']['clean_change_block_rate']) + mark) if d and 'pr_level' in d else '-', f3(h['pr_level']['clean_change_block_rate']) if h else '-']
        rows.append(row)
    print(table(['candidate', 'natural dev', 'natural held-out', 'w/o hard negatives dev', 'w/o hard negatives held-out',
                 'per-PR PR-AUC dev', 'per-PR PR-AUC held-out', 'clean PRs blocked dev', 'clean PRs blocked held-out'], rows))

    print('\n**Table 2g. Localization on failing positives with a known location** (hit: a finding within ±2 lines; IoU ≥ 0.2; median finding width in lines).\n')
    rows = []
    for c in ORDER:
        d, mark = dev_cand(c)
        h = HO['candidates'].get(c)
        row = [c]
        # out-of-fold dev runs carry scores only, no findings: their dev localization does not exist
        no_dev = bool(d) and c not in ('a-baseline', 'a-recal') and not mark
        for k in ('loc_hit', 'loc_iou20', 'loc_median_width', 'loc_n'):
            dv = d.get(k) if d and not no_dev else None
            hv = h.get(k) if h else None
            fmt = (lambda x: '-' if x is None or x != x else str(x)) if k in ('loc_median_width', 'loc_n') else f3
            row += [(fmt(dv) + mark) if d and not no_dev else '-', fmt(hv)]
        rows.append(row)
    print(table(['candidate', 'hit dev', 'hit held-out', 'IoU≥0.2 dev', 'IoU≥0.2 held-out', 'median width dev', 'median width held-out', 'n dev', 'n held-out'], rows))
    print('\nDev rows other than the baseline\'s are out-of-fold scores, which carry no findings, so dev localization exists only for a-baseline and c-llm. n0-size gives no findings by design.')
    rows = None

    print('\n**Table 2h. Held-out at the dev-matched false-alarm rate** (each candidate\'s threshold fixed on dev so that it fails 5.58% of dev\'s natural negatives, the baseline\'s own rate; `matched_thresholds.json`).\n')
    rows = []
    for c in ORDER:
        m = MATCHED['candidates'].get(c)
        v = MATCHED['vs_baseline'].get(c)
        rows.append([c, str(m.get('threshold_override') or 'own gate'), f3(m['precision']), f3(m['recall']), f3(m['fpr']),
                     diff_cell(v, 'precision') if v else '-', diff_cell(v, 'recall') if v else '-'])
    print(table(['candidate', 'threshold', 'precision', 'recall', 'false alarms', 'precision vs baseline', 'recall vs baseline'], rows))

    print('\n**Table 2i. Determinism** (verdict flips across repeated runs with every cache off; exact one-sided 95% upper bound). '
          'Dev: det100 (100 PRs, 5 runs; c-llm det30, 3 runs). Held-out: all 509 PRs, 5 runs (c-llm 30 PRs, 3 runs).\n')
    det = [('a-baseline', 'determinism/a-baseline-perfile.json', 'determinism/heldout_a-baseline.json'),
           ('c-llm', 'determinism/c-llm-perfile.json', 'determinism/heldout_c-llm.json'),
           ('d-cascade', 'determinism/d-cascade-v3.json', 'determinism/heldout_d-cascade.json')]
    rows = []
    for c, dn, hn in det:
        d, h = load(dn), load(hn)

        def cell(x, k):
            v = x[k]
            return '%d/%d = %.2f%% (≤%.2f%%)' % (v['flipped'], v.get('files', v.get('cases')), 100 * v['rate'], 100 * v['upper95'])
        rows.append([c, cell(d, 'per_file'), cell(h, 'per_file'), cell(d, 'per_pull_request'), cell(h, 'per_pull_request')])
    print(table(['candidate', 'per file dev', 'per file held-out', 'per PR dev', 'per PR held-out'], rows))
    print('\nOther candidates are deterministic by construction (b-offline, n0-size: no model call; a-recal: the baseline\'s answers) or were not run repeatedly (e-spot).')

    print('\n**Table 2j. Fix loop** (fresh coding agent per item, at most two rounds, blind judge; harness v2). Success = the gate passes, tests pass, not gamed, and the judge finds the result simpler with behaviour kept.\n')
    rows = []
    fd, fh = load('fixloop/dev_v3.json'), load('fixloop/heldout_v1.json')
    for c in ('a-baseline', 'd-cascade'):
        def s(x):
            v = x['summary'][c]
            return '%d/%d' % (v['success'], v['items']), '%d/%d' % (v['caught'], v['items']), '%d/%d' % (v['controls_blocked'], v['controls'])
        a, b = s(fd), s(fh)
        rows.append([c, a[0], b[0], a[1], b[1], a[2], b[2]])
    print(table(['candidate', 'success dev', 'success held-out', 'caught dev', 'caught held-out', 'clean controls blocked dev', 'clean controls blocked held-out'], rows))
    for name, x in (('dev', fd), ('held-out', fh)):
        v = x['vs_baseline']['d-cascade']['success']
        print('\n%s: d-cascade minus a-baseline success %+.3f [%+.3f, %+.3f] (repository bootstrap, %d repositories); exact McNemar %d vs %d discordant, p = %.3f.'
              % (name, v['diff'], v['ci95'][0], v['ci95'][1], v['clusters'], v['mcnemar']['only_candidate'], v['mcnemar']['only_baseline'], v['mcnemar']['p_two_sided']))

    print('\n**Table 2k. Cost and wall time per pull request on held-out** (509 PRs, accuracy run; c-llm\'s cost is an estimate from token counts at Haiku 5.5 list price, and its wall time excludes answer time).\n')
    cl = load('heldout_cost_latency.json')
    rows = []
    for c in ORDER:
        v = cl.get(c)
        if not v:
            rows.append([c] + ['same as a-baseline'] + [''] * 5)
            continue
        rows.append([c, '$%.4f' % v['cost_median'], '$%.4f' % v['cost_mean'], '$%.4f' % v['cost_p95'], '$%.4f' % v['cost_max'],
                     '%.1f s' % v['seconds_median'], '%.1f s' % v['seconds_p95']])
    print(table(['candidate', 'cost median', 'cost mean', 'cost p95', 'cost max', 'time median', 'time p95'], rows))

    print('\n**Table 2l. Attacks** (round 1: 51 attacks plus controls; round 2: 15; from the frozen commits). Handled = failed closed, or passed only a genuinely good change.\n')
    at = load('attacks/freeze/summary.json')
    rows = []
    for c in ORDER:
        v = at.get(c)
        r1, r2 = v['round1'], v['round2']
        rows.append([c, '%d/%d' % (r1['handled'] + r2['handled'], r1['attacks'] + r2['attacks']), 'yes' if r1['controls_ok'] and r2['controls_ok'] else 'no',
                     ', '.join(r1['not_handled'] + r2['not_handled'])])
    print(table(['candidate', 'handled', 'controls right', 'not handled'], rows))


    print('\n**Table 2m. Ablation of d-cascade\'s inputs.** Dev: repository-grouped out-of-fold, pooled and natural PR-AUC (`ablation_dcascade_dev.json`). '
          'Held-out (post hoc, not pre-registered, nothing tuned): the `raw` model applied to qualm 0.1.1\'s recorded answers (`posthoc/heldout_rawmodel.json`).\n')
    ab = load('ablation_dcascade_dev.json')
    ph = load('posthoc/heldout_rawmodel.json')
    rows = [['qualm 0.1.1 push_back alone', '%.3f' % ab['baseline_push_back_alone_dev_pr_auc'], f3(DEV['candidates']['a-baseline']['natural']['pr_auc']),
             f3(ph['candidates']['a-baseline']['pr_auc']), '']]
    for name, v in ab['feature_sets'].items():
        ho, hd = '', ''
        if name == 'raw':
            ho = f3(ph['candidates']['a-rawmodel']['pr_auc']) + ci(ph['candidates']['a-rawmodel'].get('pr_auc_ci95'))
            hd = diff_cell(ph['vs_baseline']['a-rawmodel'], 'pr_auc')
        if name == ab['chosen']:
            name += ' (d-cascade, frozen)'
            ho = f3(HO['candidates']['d-cascade']['pr_auc']) + ci(HO['candidates']['d-cascade'].get('pr_auc_ci95'))
            hd = diff_cell(HO['vs_baseline']['d-cascade'], 'pr_auc')
        rows.append([name, '%.3f' % v['all']['pr_auc'], '%.3f' % v['natural']['pr_auc'], ho, hd])
    print(table(['inputs (logistic model)', 'PR-AUC dev', 'natural PR-AUC dev', 'PR-AUC held-out', 'vs a-baseline held-out'], rows))
    print('\nraw: qualm\'s ten questions on the diff; masked: the comment-stripped view (eight of qualm\'s questions and four verbs); det: detector counts; shape: script and comment share; pieces: per-function answers.')


if __name__ == '__main__':
    main()
