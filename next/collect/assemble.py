"""Assemble the benchmark from the raw collections, split it by repository, and seal the held-out half.

    python3 -I assemble.py RAW_DIR OUT_DIR [--seed 13]

Reads RAW_DIR/{gerrit/*/,gitlab/,github/,history/}*.jsonl. Writes OUT_DIR/dev.jsonl.gz,
OUT_DIR/heldout.jsonl.gz (sealed later by seal.py) and OUT_DIR/manifest.json.

What it does, in order:
1. Drops files a reviewer wouldn't read (generated, over 200 KB, over 1,000 changed lines) and cases
   with more than 30 judged files.
2. Gives every item a stable id, removes duplicate file changes, and grades reviewer positives:
   tier A when the comment names the request outright (strong) and the author acted on it, or a
   weaker request was explicitly acknowledged; tier B for a weaker request the author only changed
   code near. Tier B positives in held-out are left unscored unless a person adjudicates them.
3. Assigns every repository to dev or held-out (tables below; small GitHub repositories by hash).
4. Within each split, injects one known smell into clean changes (mechanical.py) and makes hard
   negatives (rename, comments only, formatting, a pure move) from clean code.
5. Balances held-out to at least 30% positives by leaving surplus clean negatives unscored, never
   the paired originals of injected changes or the approved fixes of positives.
"""
import argparse, collections, difflib, glob, gzip, hashlib, json, os, random, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mechanical import INJECTORS, HARD_NEGATIVES  # noqa: E402

AI_LIKE = re.compile(r'(?i)\*\*P[0-3]\b|!\[P[0-3]|prompt for ai|ai agent|\U0001F916|generated (?:by|with)|coderabbit|<details>|severity:|'
                     r'\*\*(?:issue|problem|suggestion|why|recommendation)\*\*|^#+ |suggested (?:fix|change):|\[(?:recommended|required|optional|critical|minor)\]')
PRAISE = re.compile(r'(?i)^\W*(nice|great|good (?:catch|call|idea|job|stuff)|thanks|thank you|love|lgtm|awesome|cool|neat|excellent|perfect|\+1|yay)\b')
REQUEST = re.compile(r'(?i)\?|\bplease\b|\bcould\b|\bcan (?:we|you)\b|\bshould\b|\binstead\b|\bbut\b|\bhowever\b|\bwhy\b|\bconsider\b|\bremove\b|\bdrop\b')
NIT = re.compile(r'(?i)^\W*(nit|nits|nitpick|minor|optional|super nit|small nit|tiny nit|style nit)\b')


def usable_comment(text):
    """A reviewer comment counts as evidence unless it reads like an AI review tool or is praise without a request."""
    t = (text or '').strip()
    if not t or AI_LIKE.search(t) or len(t) > 700:
        return False
    if PRAISE.search(t) and not REQUEST.search(t):
        return False
    return True


GENERATED = re.compile(r'(?i)code generated|do not edit|@generated|auto-?generated|autogenerated')

HELDOUT_PROJECTS = {
    'go-review': {'go', 'website', 'net', 'crypto', 'sys', 'exp', 'mod', 'text', 'review', 'debug', 'benchmarks', 'perf'},
    'review': {'openstack/swift', 'openstack/manila', 'openstack/keystone', 'openstack/glance', 'openstack/octavia',
               'openstack/openstacksdk', 'openstack/watcher', 'openstack/heat', 'openstack/oslo.messaging',
               'openstack/puppet-keystone', 'openstack/puppet-neutron', 'openstack/puppet-glance', 'openstack/puppet-swift'},
    'gerrit-review': {'gerrit'},
    'chromium-review': {'devtools/devtools-frontend', 'crossbench'},
    'gitlab': {'gitlab-org/omnibus-gitlab', 'gitlab-org/gitlab-development-kit', 'gitlab-org/release-tools',
               'gitlab-org/quality/triage-ops', 'gitlab-org/gitlab-qa', 'gitlab-org/ruby/gems/gitlab-styles',
               'gitlab-org/gitaly', 'gitlab-org/cli', 'gitlab-org/gitlab-pages'},
}
# Repositories used for the agent fix loop are split by hand so each split has every language.
FIXLOOP_HELDOUT = {'tidwall/gjson', 'google/go-cmp', 'mahmoud/boltons', 'python-humanize/humanize', 'astanin/python-tabulate',
                   'unjs/pathe', 'unjs/scule', 'hanami/utils'}
FIXLOOP_DEV = {'expr-lang/expr', 'BurntSushi/toml', 'more-itertools/more-itertools', 'tkem/cachetools', 'unjs/ufo', 'unjs/defu',
               'jeremyevans/roda', 'davidteren/mutineer', 'Masterminds/semver', 'spf13/pflag', 'gobwas/glob', 'go-viper/mapstructure',
               'pytoolz/toolz', 'un33k/python-slugify', 'jaraco/inflect', 'dry-rb/dry-inflector', 'ruby/rake'}


def split_of(case):
    src, repo = case['source'], case['repo']
    if src.startswith('gerrit:'):
        host = src.split(':', 1)[1].split('.')[0]
        return 'heldout' if repo in HELDOUT_PROJECTS.get(host, set()) or (host == 'gerrit-review' and repo == 'gerrit') else 'dev'
    if src.startswith('gitlab:'):
        return 'heldout' if repo in HELDOUT_PROJECTS['gitlab'] else 'dev'
    if repo in FIXLOOP_HELDOUT:
        return 'heldout'
    if repo in FIXLOOP_DEV:
        return 'dev'
    h = int(hashlib.sha256(repo.lower().encode()).hexdigest(), 16) % 100
    return 'heldout' if h < 40 else 'dev'


def repo_key(case):
    """The repository identity the split is made on (host-qualified, so names can't collide)."""
    src = case['source']
    if src.startswith('gerrit:'):
        return src.split(':', 1)[1] + '/' + case['repo']
    if src.startswith('gitlab:'):
        return 'gitlab.com/' + case['repo']
    return 'github.com/' + case['repo']


def counts(base, head):
    a, b = (base or '').splitlines(), (head or '').splitlines()
    add = rem = 0
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, a, b).get_opcodes():
        if tag in ('replace', 'delete'):
            rem += i2 - i1
        if tag in ('replace', 'insert'):
            add += j2 - j1
    return add, rem


def sha(text):
    return hashlib.sha256((text or '').encode()).hexdigest()


def load_raw(raw):
    pats = ['gerrit/*/*.jsonl', 'gitlab/*.jsonl', 'github/github.jsonl', 'github/agent_approved.jsonl', 'history/*.jsonl']
    for p in pats:
        for f in sorted(glob.glob(os.path.join(raw, p))):
            if '/test' in f:
                continue
            for line in open(f):
                try:
                    yield json.loads(line)
                except ValueError:
                    continue  # a line cut short by a collector still writing


def tier(item):
    if item['label_source'] != 'reviewer_comment':
        return None
    acked = any(a.get('acked') for a in item.get('acted') or [])
    if item.get('strength') == 'strong' or acked:
        return 'A'
    return 'B'


def clean_case(c, seen):
    files = []
    for f in c['files']:
        head = f.get('head')
        if head is None or len(head) > 200_000 or len(f.get('base') or '') > 200_000:
            continue
        if GENERATED.search('\n'.join(head.splitlines()[:8])):
            continue
        add, rem = counts(f.get('base'), head)
        if add + rem == 0 or add + rem > 1000:
            continue
        f = dict(f, added=add, removed=rem)
        files.append(f)
    if not files or len(files) > 30:
        return None
    paths = {f['path'] for f in files}
    items = []
    for it in c['items']:
        if it['path'] not in paths:
            continue
        if it.get('label_source') == 'reviewer_comment':
            keep = [k for k, e in enumerate(it.get('evidence') or []) if usable_comment(e)]
            if not keep:
                continue  # every comment was praise or tool output: no longer a positive, and not a known negative
            if len(keep) < len(it.get('evidence') or []):
                it = dict(it, evidence=[it['evidence'][k] for k in keep], acted=[it['acted'][k] for k in keep] if it.get('acted') else it.get('acted'),
                          locations=[it['locations'][k] for k in keep] if it.get('locations') else it.get('locations'))
                if it.get('locations'):
                    it['location'] = [min(l[0] for l in it['locations']), max(l[1] for l in it['locations'])]
            it = dict(it, nit=all(NIT.search(e.strip()) for e in it['evidence']))
        f = next(x for x in files if x['path'] == it['path'])
        key = (sha(f.get('base')), sha(f['head']))
        if key in seen:
            continue
        seen.add(key)
        it = dict(it, item_id='%s::%s' % (c['case_id'], it['path']), language=f['language'], added=f['added'], removed=f['removed'],
                  agent_written=bool(c.get('agent_written')))
        t = tier(it)
        if t:
            it['tier'] = t
        items.append(it)
    if not items:
        return None
    return dict(c, files=files, items=items, repo_key=repo_key(c))


def inject_cases(cases, split, rng, per_lang):
    """One mechanical smell per host change, cycling through the smells, up to per_lang per language."""
    hosts = collections.defaultdict(list)
    for c in cases:
        for it in c['items']:
            if it['label'] == 0 and it['label_source'] in ('approved_clean', 'approved_uncommented', 'survived_90d', 'approved_agent') and it['added'] >= 8:
                hosts[it['language']].append((c, it))
    out = []
    for lang, hs in sorted(hosts.items()):
        rng.shuffle(hs)
        made = collections.Counter()
        smells = list(INJECTORS)
        for c, it in hs:
            if sum(made.values()) >= per_lang:
                break
            f = next(x for x in c['files'] if x['path'] == it['path'])
            order = sorted(smells, key=lambda s: (made[s], rng.random()))
            for smell in order:
                res = INJECTORS[smell](f.get('base'), f['head'], lang, rng)
                if not res:
                    continue
                head, loc = res
                files = [dict(x, head=head) if x['path'] == f['path'] else x for x in c['files']]
                add, rem = counts(f.get('base'), head)
                files = [dict(x, added=add, removed=rem) if x['path'] == f['path'] else x for x in files]
                cid = 'inj-%s-%s' % (smell, c['case_id'])
                item = {'path': f['path'], 'label': 1, 'label_source': 'injection_mechanical', 'smell': smell, 'location': loc,
                        'item_id': '%s::%s' % (cid, f['path']), 'language': lang, 'added': add, 'removed': rem,
                        'paired_with': it['item_id']}
                it['paired'] = True
                out.append(dict(c, case_id=cid, source='injection', files=files, items=[item], split=split,
                                origin_case=c['case_id']))
                made[smell] += 1
                break
    return out


def hard_negative_cases(cases, split, rng, per_kind_lang):
    pool = collections.defaultdict(list)
    for c in cases:
        for it in c['items']:
            if it['label'] == 0 and it['label_source'] in ('approved_clean', 'approved_uncommented', 'survived_90d'):
                f = next(x for x in c['files'] if x['path'] == it['path'])
                if 40 <= len(f['head'].splitlines()) <= 1500:
                    pool[it['language']].append((c, f))
    out = []
    for lang, fs in sorted(pool.items()):
        rng.shuffle(fs)
        made = collections.Counter()
        for c, f in fs:
            kinds = [k for k in list(HARD_NEGATIVES) + ['move'] if made[k] < per_kind_lang]
            if not kinds:
                break
            kind = rng.choice(kinds)
            if kind == 'move':
                d = os.path.dirname(f['path'])
                newp = (d + '/' if d else '') + 'internal_' + os.path.basename(f['path'])
                files = [{'path': newp, 'old_path': f['path'], 'language': lang, 'base': f['head'], 'head': f['head'], 'added': 0, 'removed': 0}]
                item_path = newp
            else:
                res = HARD_NEGATIVES[kind](f['head'], lang, rng)
                if not res:
                    continue
                base, head = res
                add, rem = counts(base, head)
                if add + rem == 0:
                    continue
                files = [{'path': f['path'], 'language': lang, 'base': base, 'head': head, 'added': add, 'removed': rem}]
                item_path = f['path']
            cid = 'hn-%s-%s-%s' % (kind, c['case_id'], hashlib.sha256(f['path'].encode()).hexdigest()[:6])
            out.append(dict(c, case_id=cid, source='hard_negative', files=files, split=split, origin_case=c['case_id'],
                            items=[{'path': item_path, 'label': 0, 'label_source': 'hard_negative', 'smell': kind,
                                    'item_id': '%s::%s' % (cid, item_path), 'language': lang,
                                    'added': files[0]['added'], 'removed': files[0]['removed']}]))
            made[kind] += 1
    return out


def balance(cases, rng, min_pos_rate):
    items = [it for c in cases for it in c['items'] if it.get('label') is not None]
    pos = sum(1 for it in items if it['label'] == 1)
    neg = [it for it in items if it['label'] == 0 and not it.get('paired') and it['label_source'] in ('approved_clean', 'approved_uncommented', 'survived_90d')]
    total = len(items)
    need_drop = 0
    while total - need_drop > 0 and pos / (total - need_drop) < min_pos_rate:
        need_drop += 1
    rng.shuffle(neg)
    for it in neg[:need_drop]:
        it['unscored'] = 'balance'
        it['label_was'] = it['label']
        it['label'] = None
    return need_drop


def cap(cases, rng, n_target, pos_rate):
    """Pre-registered random subsample of held-out down to n_target scored items, stratified by
    language and label source, before any candidate exists. Paired items are kept together:
    an injected positive keeps its clean original, and the rest of the negatives fill the gap."""
    items = [it for c in cases for it in c['items'] if it.get('label') is not None]
    if len(items) <= n_target:
        return 0
    pos = [it for it in items if it['label'] == 1]
    neg = [it for it in items if it['label'] == 0]
    want_pos = min(len(pos), round(n_target * pos_rate))
    strata = collections.defaultdict(list)
    for it in pos:
        strata[(it['language'], it['label_source'])].append(it)
    keep = {it['item_id'] for it in pos if it.get('agent_written')}  # the agent-written subset is small: keep all of it
    for k in sorted(strata):
        strata[k].sort(key=lambda it: it['item_id'])
        rng.shuffle(strata[k])
    # round-robin over strata in proportion to their size
    while len(keep) < want_pos:
        for k in sorted(strata):
            share = len(strata[k]) / len(pos)
            taken = sum(1 for it in strata[k] if it['item_id'] in keep)
            if strata[k] and taken < round(share * want_pos + 0.5) and len(keep) < want_pos:
                for it in strata[k]:
                    if it['item_id'] not in keep:
                        keep.add(it['item_id'])
                        break
    by_id = {it['item_id']: it for it in items}
    must = {by_id[it['paired_with']]['item_id'] for it in pos if it['item_id'] in keep and it.get('paired_with') in by_id}
    must |= {it['item_id'] for it in neg if it['label_source'] in ('hard_negative',) or it.get('agent_written')}
    want_neg = n_target - len(keep)
    rest = sorted((it for it in neg if it['item_id'] not in must), key=lambda it: it['item_id'])
    rng.shuffle(rest)
    neg_keep = sorted(must)[:want_neg] + [it['item_id'] for it in rest][:max(0, want_neg - len(must))]
    keep |= set(neg_keep)
    dropped = 0
    for it in items:
        if it['item_id'] not in keep:
            it['unscored'] = 'size_cap'
            it['label_was'] = it['label']
            it['label'] = None
            dropped += 1
    return dropped


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('raw')
    ap.add_argument('out')
    ap.add_argument('--seed', type=int, default=13)
    ap.add_argument('--inject-per-lang', type=int, default=24)
    ap.add_argument('--hardneg-per-kind-lang', type=int, default=4)
    ap.add_argument('--min-pos-rate', type=float, default=0.30)
    ap.add_argument('--heldout-size', type=int, default=600)
    ap.add_argument('--heldout-pos-rate', type=float, default=0.35)
    a = ap.parse_args()
    rng = random.Random(a.seed)
    seen, cases = set(), []
    for c in load_raw(a.raw):
        c = clean_case(c, seen)
        if c:
            c['split'] = split_of(c)
            cases.append(c)
    by_split = {'dev': [c for c in cases if c['split'] == 'dev'], 'heldout': [c for c in cases if c['split'] == 'heldout']}
    for split, cs in by_split.items():
        cs += inject_cases(list(cs), split, random.Random('%d-inj-%s' % (a.seed, split)), a.inject_per_lang)
        cs += hard_negative_cases(list(cs), split, random.Random('%d-hn-%s' % (a.seed, split)), a.hardneg_per_kind_lang)
    # Tier B positives in held-out wait for a person; until then they are not scored.
    for c in by_split['heldout']:
        for it in c['items']:
            if it.get('tier') == 'B':
                it['unscored'] = 'tier_b_pending_adjudication'
                it['label_was'] = it['label']
                it['label'] = None
    dropped = balance(by_split['heldout'], random.Random('%d-bal' % a.seed), a.min_pos_rate)
    capped = cap(by_split['heldout'], random.Random('%d-cap' % a.seed), a.heldout_size, a.heldout_pos_rate)
    # LLM-written injections into tested repositories (the fix-loop items) are always scored.
    for split in ('dev', 'heldout'):
        p = os.path.join(a.raw, 'fixloop', 'fixloop_%s.jsonl' % split)
        if os.path.exists(p):
            for line in open(p):
                c = clean_case(json.loads(line), seen)
                if c:
                    c['split'] = split
                    by_split[split].append(c)
    os.makedirs(a.out, exist_ok=True)
    manifest = {'seed': a.seed, 'balanced_out_heldout_negatives': dropped, 'capped_heldout_items': capped, 'splits': {}}
    repos_by_split = collections.defaultdict(set)
    for split, cs in by_split.items():
        cs.sort(key=lambda c: c['case_id'])
        path = os.path.join(a.out, '%s.jsonl.gz' % split)
        reserve = [c for c in cs if not any(it.get('label') is not None for it in c['items'])]
        cs[:] = [c for c in cs if any(it.get('label') is not None for it in c['items'])]
        with gzip.GzipFile(path, 'wb', mtime=0) as fh:
            for c in cs:
                fh.write((json.dumps(c, sort_keys=True) + '\n').encode())
                repos_by_split[split].add(c['repo_key'])
        if reserve:
            with gzip.GzipFile(os.path.join(a.out, '%s_reserve.jsonl.gz' % split), 'wb', mtime=0) as fh:
                for c in reserve:
                    fh.write((json.dumps(c, sort_keys=True) + '\n').encode())
        items = [it for c in cs for it in c['items']]
        scored = [it for it in items if it.get('label') is not None]
        stat = collections.Counter()
        for it in scored:
            stat['%s|%s|%d' % (it['language'], it['label_source'], it['label'])] += 1
        manifest['splits'][split] = {
            'cases': len(cs), 'items': len(items), 'scored_items': len(scored),
            'positives': sum(it['label'] for it in scored), 'repos': len(repos_by_split[split]),
            'agent_written_scored': sum(1 for c in cs if c.get('agent_written') for it in c['items'] if it.get('label') is not None),
            'by_language_source_label': dict(sorted(stat.items())),
            'unscored': dict(collections.Counter(it.get('unscored') for it in items if it.get('unscored'))),
        }
    overlap = repos_by_split['dev'] & repos_by_split['heldout']
    manifest['repo_overlap'] = sorted(overlap)
    json.dump(manifest, open(os.path.join(a.out, 'manifest.json'), 'w'), indent=1, sort_keys=True)
    for split, m in manifest['splits'].items():
        print(split, {k: v for k, v in m.items() if k not in ('by_language_source_label',)})
    print('repo overlap between splits:', len(overlap))


if __name__ == '__main__':
    main()
